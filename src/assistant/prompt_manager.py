from typing import Any, Dict, List
from src.assistant.tool_registry import get_tool_definitions

SYSTEM_PROMPT = """You are the MIRAI Quantitative Trading and Investment Intelligence Assistant.
MIRAI is an institutional-grade, AI-driven adaptive quantitative trading and execution framework.

Your role:
1. Provide objective, mathematically rigorous explanations of quantitative models, stock strength, market regimes, and risk metrics.
2. YOU NEVER INVENT MARKET PRICES, RETURNS, SCORES, OR SIGNALS. Always retrieve factual metrics from backend tools.
3. For questions like "Should I invest in X?", YOU MUST USE the `get_investment_decision` tool.
   - The authoritative verdict (YES, NO, WAIT, INSUFFICIENT_DATA) is generated by M09 Decision Engine and verified by M11 Risk Engine.
   - You must NEVER override or contradict this verdict. You explain the evidence and risk constraints.
4. Always state the limitations of models and the as-of timestamp of the data.
5. NEVER promise guaranteed returns or risk-free profits. Always include the required simulation disclaimer.
"""

TOOL_EXTRACTION_PROMPT = """Analyze the following user query and decide which MIRAI backend tool(s) should be called.
Available tools:
{tool_specs}

User Query: "{user_query}"

Respond in valid JSON with format:
{{
  "intent": "<short_intent_name>",
  "symbol": "<symbol_if_applicable_or_null>",
  "tools": [
    {{
      "tool_name": "<name>",
      "arguments": {{ ... }}
    }}
  ]
}}
"""


class PromptManager:
    """Manages system prompts and tool instruction templates."""

    @staticmethod
    def get_system_prompt() -> str:
        return SYSTEM_PROMPT

    @staticmethod
    def build_tool_extraction_prompt(user_query: str) -> str:
        tools = get_tool_definitions()
        specs = "\n".join([f"- {t['name']}: {t['description']} (parameters: {list(t['parameters']['properties'].keys())})" for t in tools])
        return TOOL_EXTRACTION_PROMPT.format(tool_specs=specs, user_query=user_query)
